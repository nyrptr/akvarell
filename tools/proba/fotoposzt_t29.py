# Tervező (ZSEBMARKETING, 11-27): mód-váltás, három kérdés, 4 hetes naptár, képtartalék, fotókérés, mentés, sorra koppintás → poszt mód.
import asyncio,sys
from playwright.async_api import async_playwright
URL=sys.argv[1] if len(sys.argv)>1 else 'http://127.0.0.1:8788/fotoposzt/'
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(); hib=[]
    for w in (390,1280):
      pg=await b.new_page(viewport={'width':w,'height':900}); err=[]; pg.on('pageerror',lambda e:err.append(str(e)))
      await pg.goto(URL); await pg.wait_for_timeout(2500)
      await pg.click('#modok button[data-mod=terv]')
      if await pg.is_hidden('#terv'): hib.append(f'{w}: terv nem nyílt')
      if not await pg.is_hidden('#lepsor'): hib.append(f'{w}: lépéssor látszik terv módban')
      if not await pg.is_disabled('#tervKeszit'): hib.append(f'{w}: gomb aktív kérdések nélkül')
      for d in ('tervCel','tervKinek','tervHeti'): await pg.click(f'#{d} .chip >> nth=0')
      await pg.click('#tervKeszit'); await pg.wait_for_timeout(300)
      n=await pg.locator('.tervsor').count()
      if n!=8: hib.append(f'{w}: heti 2 × 4 hét = 8 sor helyett {n}')
      cta=await pg.locator('.tervsor:has-text("hívás a foglalásra")').count()
      if not (1<=cta<=n//2): hib.append(f'{w}: hívás aránya rossz ({cta}/{n})')
      if await pg.locator('.tervfoto li').count()<3: hib.append(f'{w}: kevés fotókérés')
      if await pg.locator('.tervfoto li:has-text("Ha arra jársz")').count()!=1: hib.append(f'{w}: időjárás nem lehetőségként')
      bad=await pg.evaluate("()=>[...document.querySelectorAll('.tervsor')].filter(e=>e.textContent.includes('hívás')&&/Vevőút: (meglát|elképzeli)/.test(e.textContent)).length")
      if bad: hib.append(f'{w}: hívás figyelemkeltő lépésen ({bad})')
      sw=await pg.evaluate("()=>document.documentElement.scrollWidth>innerWidth+1")
      if sw: hib.append(f'{w}: vízszintes kicsúszás')
      small=await pg.evaluate("()=>[...document.querySelectorAll('#terv button')].filter(e=>e.offsetParent&&e.getBoundingClientRect().height<44).length")
      if small: hib.append(f'{w}: {small} gomb 44px alatt')
      # tisztán: képtartalék logika
      r=await pg.evaluate("""()=>{const t=__terv.naptar({cel:'x',kinek:'y',heti:5},'2026-01-05');return {n:t.helyek.length,ev:t.helyek[0].evszak,ures:t.helyek.filter(h=>!h.tema).length,csere:t.helyek.filter(h=>h.csere).every(h=>__terv.vanAnyag(h.tema,h.evszak))}}""")
      if r['n']!=20 or r['ev']!='tel' or r['ures'] or not r['csere']: hib.append(f'{w}: naptar() {r}')
      await pg.click('#modok button[data-mod=ered]'); await pg.wait_for_timeout(200)
      if await pg.is_hidden('#ered') or not await pg.is_hidden('#terv'): hib.append(f'{w}: eredmény mód nem nyílt')
      if 'BEMUTATÓ' not in await pg.inner_text('#ered'): hib.append(f'{w}: nincs bemutató-jelölés')
      if await pg.locator('.kampkartya').count()<1: hib.append(f'{w}: nincs kampánykártya')
      if f'/ {n} poszt kint' not in await pg.inner_text('.kampkartya >> nth=0'): hib.append(f'{w}: kártyán nincs haladás')
      if await pg.locator('.kampkartya .javaslat').count()<1: hib.append(f'{w}: nincs javaslat a kártyán')
      if await pg.locator('#eredLista details >> nth=0').get_attribute('open') is not None: hib.append(f'{w}: a részletek alapból nyitva')
      if await pg.locator('#tervCel .chip').count()!=2: hib.append(f'{w}: a cél nem 2 választás')
      await pg.reload(); await pg.wait_for_timeout(2500); await pg.click('#modok button[data-mod=terv]')
      if await pg.locator('.tervsor').count()!=8: hib.append(f'{w}: a terv nem maradt meg újratöltés után')
      await pg.click('.tervsor >> nth=0'); await pg.wait_for_timeout(300)
      if not await pg.is_hidden('#terv') or await pg.is_hidden('#lepsor'): hib.append(f'{w}: sorra koppintás nem vitt poszt módba')
      await pg.click('#modok button[data-mod=poszt]'); await pg.wait_for_timeout(200)
      if await pg.is_hidden('#demoW'): hib.append(f'{w}: bemutató képtár nem látszik')
      await pg.click('#demoKepek .chip >> nth=0'); await pg.wait_for_timeout(2500)
      await pg.evaluate("()=>lep(2)"); await pg.wait_for_timeout(300)
      if await pg.is_hidden('#miniFoto'): hib.append(f'{w}: a 2. lépésnél nem látszik a fotó')
      await pg.evaluate("()=>lep(1)"); await pg.wait_for_timeout(200)
      if not await pg.is_hidden('#miniFoto'): hib.append(f'{w}: az 1. lépésnél fölöslegesen látszik a mini')
      if await pg.is_hidden('#prev'): hib.append(f'{w}: bemutató fotó nem töltődött be')
      await pg.click('#modok button[data-mod=terv]'); await pg.click('.tervsor >> nth=0'); await pg.wait_for_timeout(2500)
      if await pg.is_hidden('#prev'): hib.append(f'{w}: terv-sorról nem jött fotó')
      r=await pg.evaluate("()=>{document.getElementById('demoKi').click();return JSON.parse(localStorage.getItem('akvposzt-kint')||'[]')[0]}")
      if not r or not r.get('tema'): hib.append(f'{w}: szimulált kiküldés nem rögzült ({r})')
      await pg.click('#modok button[data-mod=ered]'); await pg.wait_for_timeout(200)
      if '✓ kint' not in await pg.text_content('#eredLista'): hib.append(f'{w}: a kiküldött poszt nem jelent meg „kint”-ként')
      if not (await pg.inner_text('.kampkartya >> nth=0')).count('1 / '): hib.append(f'{w}: a haladás nem lett 1')
      h=await pg.evaluate("()=>[document.getElementById('fejCim').textContent,getComputedStyle(document.documentElement).getPropertyValue('--deep').trim()]")
      if h[0]!='Akvarell Apartmanház' or h[1]!='#1d5a8c': hib.append(f'{w}: arculat nem töltődött ({h})')
      await pg.click('#modok button[data-mod=poszt]')
      if await pg.is_hidden('#frissSav'): hib.append(f'{w}: frissítés-sáv nem látszik')
      await pg.click('#frissLe'); await pg.wait_for_timeout(3500)
      k=await pg.evaluate("()=>JSON.parse(document.getElementById('keszlet').textContent).zaro.filter(z=>z.id.startsWith('f1-')).length")
      if k!=4: hib.append(f'{w}: frissítés nem került a készletbe ({k})')
      if 'Frissítve' not in await pg.inner_text('#frissSav'): hib.append(f'{w}: nincs „Frissítve” jelzés')
      await pg.click('#frissSav .chip'); await pg.wait_for_timeout(3500)
      k=await pg.evaluate("()=>JSON.parse(document.getElementById('keszlet').textContent).zaro.filter(z=>z.id.startsWith('f1-')).length")
      if k!=0: hib.append(f'{w}: visszaállítás nem működött')
      if err: hib.append(f'{w}: JS {err[0]}')
      await pg.screenshot(path=f'/tmp/terv-{w}.png',full_page=False)
      await pg.close()
    for h in hib: print('HIBA',h)
    print(len(hib),'HIBA'); await b.close()
asyncio.run(main())
